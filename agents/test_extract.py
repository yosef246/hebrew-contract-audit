# תת-סעיפים (1.א, 1.1) + סעיף ענק (>1500) כדי לאלץ windowing → mixed
_BIG = ("השוכר מתחייב לשמור על הדירה, לשלם את כל התשלומים השוטפים במועדם, "
        "להימנע מכל שינוי מבני, ולהחזיר את הדירה במצב תקין בתום השכירות. ") * 12
DOC_B = f"""הסכם שכירות

1. הגדרות.
1.א המשכיר הוא הבעלים הרשום של הדירה.
1.1 השוכר הוא הצד השוכר את הדירה למגורים.
2. חובות השוכר. {_BIG}
3. סיום. כל צד רשאי לסיים בהודעה מראש של 30 יום."""

# מספור אותיות בלבד (א., ב.) — regex דורש ספרה → אמור לפספס → fallback
DOC_C = """חוזה שכירות

א. הצדדים. המשכיר והשוכר מסכימים כדלקמן.
ב. המושכר. דירת 2 חדרים ברחוב ויצמן 5.
ג. התמורה. דמי שכירות בסך 4,000 ₪ לחודש.
ד. סיום. כל צד רשאי לסיים בהודעה מראש."""

def show(name, raw):
    print(f"\n{'='*60}\n{name}\n{'='*60}")
    clauses, tele = extract_clauses(raw)
    print(f"telemetry: path={tele.path} n_clauses={tele.n_clauses} "
          f"avg_len={tele.avg_len} regex_sections={tele.regex_sections} "
          f"fallback_reason={tele.fallback_reason}")
    for c in clauses:
        print(f"   [{c.index}] section={c.section_number!r:8} len={len(c.text):4}  {c.text[:45].replace(chr(10),' ')}...")

if __name__ == "__main__":
    show("DOC A — ממוספר תקין (1. 2. 3.)", DOC_A)
    show("DOC B — תת-סעיפים (1.א, 1.1) + סעיף ענק", DOC_B)
    show("DOC C — אותיות בלבד (א. ב. ג.)", DOC_C)
